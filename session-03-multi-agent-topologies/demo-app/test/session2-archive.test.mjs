import test from "node:test";
import assert from "node:assert/strict";
import { appendFile, mkdtemp, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createExecutionLog } from "../src/execution-log.mjs";
import { createTrace } from "../src/trace.mjs";

test("repeated payloads share storage and remain complete after reopening", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "execution-objects-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const payload = "Complete captured tool observation. ".repeat(12000);
  const log = createExecutionLog({ directory, scopeId: "fixture" });
  for (const id of ["one", "two", "three"])
    log.record({ id, kind: "model", operationId: id, payload });
  await log.flush();
  assert.equal((await readdir(join(directory, "objects"))).length, 1);
  assert.ok(log.summary().storedBytes < Buffer.byteLength(payload) * 1.1);
  assert.equal((await log.get("two")).payload, payload);
  assert.equal(log.list({ limit: 2 }).records[0].payload, undefined);
  await log.close();
  const reopened = createExecutionLog({ directory, scopeId: "fixture" });
  assert.equal((await reopened.get("one")).payload, payload);
  assert.equal(reopened.summary().totalRecords, 3);
  await reopened.close();
});

test("an interrupted journal tail preserves earlier records and new capture uses a fresh segment", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "execution-tail-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const log = createExecutionLog({ directory, scopeId: "fixture" });
  log.record({ id: "before", kind: "editor", action: "saved" });
  await log.close();
  const segment = (await readdir(directory)).find((name) => name.endsWith(".ndjson"));
  await appendFile(join(directory, segment), '{"interrupted":');
  const next = createExecutionLog({ directory, scopeId: "fixture" });
  assert.equal((await next.get("before")).action, "saved");
  assert.equal(next.summary().capture.status, "partial");
  next.record({ id: "after", kind: "editor", action: "saved again" });
  await next.close();
  const recovered = createExecutionLog({ directory, scopeId: "fixture" });
  assert.equal((await recovered.get("after")).action, "saved again");
  assert.equal(recovered.summary().totalRecords, 2);
  await recovered.close();
});

test("clear retains pending writes, payloads, costs and late span finishes through multiple resets and reload", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "execution-generations-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const trace = createTrace({ directory, scopeId: "paper" });
  const payload = "Complete original observation. ".repeat(3000);
  const task = trace.start("story", { jobId: "earlier-job", payload });
  const span = trace.start("model", { jobId: "earlier-job", operationId: "charged" });
  trace.record("agent", { jobId: "earlier-job", action: "job_progress", phase: "researching" });
  const previousPage = trace.list({ view: "protocol", limit: 1 });
  assert.ok(previousPage.nextCursor);
  const clearing = trace.clear();
  span.finish({ costUsd: 0.012, result: { text: "Late result retained" } });
  task.finish({ status: "completed", answer: "Original response" });
  const lateProgress = trace.record("agent", { jobId: "earlier-job", action: "job_progress",
    status: "completed", answer: "Original response" });
  await clearing;
  const fresh = trace.record("editor", { action: "stage_changed" });
  assert.equal(trace.generation, 1);
  assert.equal(trace.list().total, 1);
  assert.equal(trace.list({ view: "protocol" }).total, 1);
  assert.equal(trace.summary().totalRecords, 1);
  assert.equal(trace.list().records[0].id, fresh.id);
  assert.equal((await trace.get(lateProgress.id)).generation, 0);
  assert.equal((await trace.get(span.id)).result.text, "Late result retained");
  assert.equal(trace.summary().requestCount, 1);
  assert.equal(trace.summary().reportedCostUsd, 0.012);
  assert.equal(trace.summary().archivedRecords, 4);
  assert.throws(() => trace.list({ view: "protocol", cursor: previousPage.nextCursor }), /generation/);
  await trace.clear();
  assert.equal(trace.summary().totalRecords, 0);
  assert.equal(trace.summary().teachingRecords, 0);
  assert.equal(trace.list({ view: "protocol" }).total, 0);
  assert.equal(trace.list({ view: "teaching" }).total, 0);
  assert.deepEqual(trace.recent({ view: "protocol" }), []);
  assert.deepEqual(trace.recent({ view: "teaching" }), []);
  const settlement = trace.record("inference.settlement", { operationId: "charged", costUsd: 0.012 });
  assert.equal(settlement.generation, 0);
  assert.equal(trace.list({ view: "protocol" }).total, 0);
  const newest = trace.record("editor", { action: "new_newspaper" });
  await trace.close();

  const restored = createTrace({ directory, scopeId: "paper" });
  t.after(() => restored.close());
  await restored.restore();
  assert.equal(restored.generation, 2);
  assert.deepEqual(restored.list().records.map((record) => record.id), [newest.id]);
  assert.equal(restored.summary().archivedRecords, 6);
  assert.equal(restored.list({ view: "protocol" }).total, 1);
  assert.equal(restored.summary().totalRecords, 1);
  assert.equal(restored.list({ view: "protocol", taskId: "earlier-job" }).total, 0);
  assert.equal(restored.list({ view: "protocol", scope: "all" }).total, 7);
  assert.equal(restored.list({ view: "protocol", scope: "all", taskId: "earlier-job" }).total, 4);
  assert.equal((await restored.get(task.id)).payload, payload);
  assert.equal((await restored.get(task.id)).answer, "Original response");
  assert.equal((await restored.get(span.id)).costUsd, 0.012);
  assert.equal(restored.describe(task.id).detailAvailable, true);
  assert.equal(restored.summary().requestCount, 1);
  assert.equal(restored.summary().capture.status, "complete");
  assert.equal(restored.summary().retention.clear, "new-visible-generation");
  assert.equal(restored.entries.length, 7);
  const files = await readdir(directory);
  assert.ok(files.some((name) => name.endsWith(".ndjson")));
  assert.ok((await readdir(join(directory, "objects"))).length > 0);
});
